// ─── Fixture (generated by scripts/generate-pol-measures-golden.py from the real package) ─────

type Encoded = number | "NaN" | "Infinity" | "-Infinity";
interface PyError {
  type: string;
  message: string;
  at?: "constructor";
}
interface Fixture {
  header: Record<string, string>;
  cases: Array<{ id: string; k: number; counts: number[]; x: number[]; weights: number[] }>;
  results: Array<{
    measure: string;
    params: Record<string, number | string | null>;
    values: Array<Encoded | { error: PyError }>;
    labels3?: string[];
    labelsAll?: Array<Record<string, Record<string, string>> | { error: string }>;
  }>;
  special: Array<{
    id: string;
    measure: string;
    params: Record<string, number | string | null>;
    x: number[];
    weights: number[];
    options: { normalize_weights?: boolean; normalize_positions?: boolean };
    value?: Encoded;
    error?: PyError;
  }>;
  bisection: Array<{ case: string; alpha: number; beta: number; value: Encoded }>;
}

const fixture: Fixture = JSON.parse(
  readFileSync(join(import.meta.dirname, "__fixtures__", "pol-measures-golden.json"), "utf8"),
);

/** Max relative error accepted against the Python package. */
const REL_TOL = 1e-9;

function decode(value: Encoded): number {
  if (value === "NaN") return Number.NaN;
  if (value === "Infinity") return Number.POSITIVE_INFINITY;
  if (value === "-Infinity") return Number.NEGATIVE_INFINITY;
  return value;
}

function relativeError(actual: number, expected: number): number {
  if (Number.isNaN(expected)) return Number.isNaN(actual) ? 0 : Number.POSITIVE_INFINITY;
  if (actual === expected) return 0;
  const scale = Math.max(Math.abs(actual), Math.abs(expected));
  return Math.abs(actual - expected) / scale;
}

function build(
  measure: string,
  params: Record<string, number | string | null>,
): PolarizationMeasure {
  const alpha = params.alpha as number;
  const beta = params.beta as number;
  const alienationName = params.alienation as string | undefined;
  const alienation =
    alienationName === "d-1"
      ? (d: number) => d - 1
      : alienationName === undefined
        ? null
        : ALIENATIONS[alienationName as AlienationId];
  const K = (params.K as number | null | undefined) ?? null;
  switch (measure) {
    case "EstebanRay":
      return new EstebanRay(alpha, K);
    case "GeneralizedER":
      return new GeneralizedER(alpha, alienation, K);
    case "EMDPol":
      return new EMDPol();
    case "Experts":
      return new Experts();
    case "ShannonPol":
      return new ShannonPol();
    case "VanDerEijkPol":
      return new VanDerEijkPol();
    case "MEC":
      return new MEC(alpha, beta);
    case "MECNormalized":
      return new MECNormalized(alpha, beta);
    case "GeneralizedMEC":
      return new GeneralizedMEC(alpha, alienation);
    case "BiPol":
      return new BiPol();
    default:
      throw new Error(`unknown measure ${measure}`);
  }
}

function captureError(fn: () => unknown): PolarizationError {
  try {
    fn();
  } catch (err) {
    if (err instanceof PolarizationError) return err;
    throw err;
  }
  throw new Error("expected a PolarizationError");
}

// ─── Tests ───────────────────────────────────────────────────────────────────────────────────

describe("pol_measures golden fixture", () => {
  it("records the package commit and the generator command", () => {
    expect(fixture.header.commit).toMatch(/^0e05564/);
    expect(fixture.header.generator).toBe("scripts/generate-pol-measures-golden.py");
    expect(fixture.header.command).toContain("python -I");
  });

  it("feeds the measures the same positions and weights as the fixture, bit for bit", () => {
    for (const c of fixture.cases) {
      expect(Array.from(categoryPositions(c.k))).toEqual(c.x);
      // The run pipeline: counts in the fine histogram → rebinned to k → fractions
      const fine = new Uint32Array(FINE_BINS);
      c.counts.forEach((count, j) => {
        fine[j * (FINE_BINS / c.k)] = count;
      });
      const weights = rebinCounts(fine, c.k);
      toWeights(weights);
      expect(Array.from(weights)).toEqual(c.weights);
    }
  });

  const maxErrorByMeasure = new Map<string, number>();

  describe.each(
    fixture.results.map((r) => [`${r.measure} ${JSON.stringify(r.params)}`, r] as const),
  )("%s", (_name, result) => {
    it("matches every histogram within 1e-9 relative", () => {
      fixture.cases.forEach((c, i) => {
        const expected = result.values[i];
        if (typeof expected === "object" && expected !== null) {
          const err = captureError(() => build(result.measure, result.params).call(c.x, c.weights));
          expect([c.id, err.pythonType, err.message]).toEqual([
            c.id,
            expected.error.type,
            expected.error.message,
          ]);
          return;
        }
        const actual = build(result.measure, result.params).call(c.x, c.weights);
        const error = relativeError(actual, decode(expected as Encoded));
        maxErrorByMeasure.set(
          result.measure,
          Math.max(maxErrorByMeasure.get(result.measure) ?? 0, error),
        );
        expect(error, `${c.id}: ${actual} vs ${String(expected)}`).toBeLessThanOrEqual(REL_TOL);
      });
    });

    if (result.labels3 !== undefined) {
      it("classifies like the package (labels=3, kmeans)", () => {
        fixture.cases.forEach((c, i) => {
          const [, label] = build(result.measure, result.params).callWithLabels(c.x, c.weights, 3);
          expect([c.id, label]).toEqual([c.id, result.labels3?.[i]]);
        });
      });
    }

    if (result.labelsAll !== undefined) {
      it("returns every classification like the package (labels='all')", () => {
        fixture.cases.forEach((c, i) => {
          const all = build(result.measure, result.params).callWithAllLabels(c.x, c.weights);
          const expected = result.labelsAll?.[i];
          if (expected !== undefined && "error" in expected) {
            expect([c.id, all.error, all.classifications]).toEqual([c.id, expected.error, {}]);
            return;
          }
          const actual: Record<string, Record<string, string>> = {};
          for (const [method, perCount] of Object.entries(all.classifications)) {
            actual[method] = Object.fromEntries(
              Object.entries(perCount).map(([n, label]) => [String(n), label]),
            );
          }
          expect([c.id, actual]).toEqual([c.id, expected]);
        });
      });
    }
  });

  describe("validation, options and error semantics", () => {
    it.each(fixture.special.map((s) => [s.id, s] as const))("%s", (_id, special) => {
      const options = {
        normalizeWeights: special.options.normalize_weights,
        normalizePositions: special.options.normalize_positions,
      };
      const run = () =>
        build(special.measure, special.params).call(special.x, special.weights, options);
      if (special.error !== undefined) {
        const err = captureError(run);
        expect([err.pythonType, err.message]).toEqual([special.error.type, special.error.message]);
        return;
      }
      const error = relativeError(run(), decode(special.value as Encoded));
      expect(error).toBeLessThanOrEqual(REL_TOL);
    });
  });

  describe("utils.optimization.mec_bisection_value", () => {
    it("matches the package's reference optimizer", () => {
      const byId = new Map(fixture.cases.map((c) => [c.id, c]));
      for (const entry of fixture.bisection) {
        const c = byId.get(entry.case);
        if (c === undefined) throw new Error(`missing case ${entry.case}`);
        const actual = mecBisectionValue(c.x, c.weights, { alpha: entry.alpha, beta: entry.beta });
        const error = relativeError(actual, decode(entry.value));
        maxErrorByMeasure.set(
          "mec_bisection_value",
          Math.max(maxErrorByMeasure.get("mec_bisection_value") ?? 0, error),
        );
        expect(error).toBeLessThanOrEqual(REL_TOL);
      }
    });
  });

  it("keeps every measure's maximum relative error within 1e-9", () => {
    // Measured at 0 for all but GeneralizedER (~7e-16: Math.exp vs libm) and GeneralizedMEC
    // (~3e-10: those ulps reach the optimizer's comparisons near a flat minimum).
    expect(maxErrorByMeasure.size).toBeGreaterThanOrEqual(10);
    for (const value of maxErrorByMeasure.values()) expect(value).toBeLessThanOrEqual(REL_TOL);
  });
});
